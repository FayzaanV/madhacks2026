#!/usr/bin/env python3
"""Regenerate lib/test-vectors.json from the Python reference implementation.

Run only when the math intentionally changes, then make the TypeScript match:
  python3 scripts/gen_test_vectors.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "databricks", "lib"))
import clout as c  # noqa: E402

lmsr_cases = [
    {"q": [0, 0], "b": 500, "i": 0, "amount": 10},
    {"q": [0, 0], "b": 500, "i": 1, "amount": 100},
    {"q": [300, -50], "b": 500, "i": 1, "amount": 25},
    {"q": [0, 0, 0, 0], "b": 300, "i": 2, "amount": 40},
    {"q": [5000, 0], "b": 100, "i": 1, "amount": 10},      # overflow guard
    {"q": [120, 80, -40], "b": 250, "i": 0, "amount": 0.5},
]
lmsr = []
for case in lmsr_cases:
    q, b, i, a = case["q"], case["b"], case["i"], case["amount"]
    q2, shares, post = c.apply_trade(q, i, a, b)
    lmsr.append({**case,
                 "cost": c.cost(q, b),
                 "prices": c.prices(q, b),
                 "shares": shares,
                 "cost_check": c.cost_to_buy(q, i, shares, b),
                 "new_q": q2,
                 "post_price": post})

vectors = {
    "_comment": "Generated by scripts/gen_test_vectors.py from databricks/lib/clout.py. Do not edit by hand.",
    "tolerance": 1e-9,
    "lmsr": lmsr,
    "starting_clout": c.STARTING_CLOUT,
    "can_afford": [{"balance": b, "amount": a, "ok": c.can_afford(b, a)}
                   for b, a in [(100, 30), (100, 100), (100, 100.01), (0, 1), (-5, 1), (50, 0), (50, -3)]],
    "privileges": [{"clout": x, "privileges": c.privileges(x)} for x in [-20, 0, 249, 250, 500, 999, 1000]],
    "net_clout_change": [
        {"trades": [[0, 10, 19.9], [1, 5, 10.2]], "winner": 0,
         "net": c.net_clout_change([(0, 10, 19.9), (1, 5, 10.2)], 0)},
        {"trades": [[0, 10, 19.9], [1, 5, 10.2]], "winner": 1,
         "net": c.net_clout_change([(0, 10, 19.9), (1, 5, 10.2)], 1)},
    ],
    "smart_money": [
        {"stakes": s, "n": n, "smart_money": c.smart_money(s, n)}
        for s, n in [
            ([[800, 0, 50], [400, 1, 20], [-30, 1, 10], [0, 1, 10]], 2),
            ([[-5, 0, 10], [0, 1, 10]], 2),
            ([[100, 2, 10], [300, 0, 10], [50, 2, 40]], 3),
        ]
    ],
    "brier": [{"f": f, "o": o, "brier": c.brier(f, o)} for f, o in [(0.7, 1), (0.7, 0), (0.0, 0), (1.0, 0)]],
    "calibration": {
        "pairs": [[0.05, 0], [0.12, 0], [0.18, 1], [0.71, 1], [0.74, 1], [0.79, 0], [0.95, 1], [1.0, 1]],
    },
}
vectors["calibration"]["curve"] = c.calibration_curve(vectors["calibration"]["pairs"])
vectors["calibration"]["mean_brier"] = c.mean_brier(vectors["calibration"]["pairs"])

out = os.path.join(ROOT, "lib", "test-vectors.json")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as fh:
    json.dump(vectors, fh, indent=2)
    fh.write("\n")
print("wrote", os.path.relpath(out, ROOT))
